package com.learning.auction.bid;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.UUID;

import org.springframework.data.domain.Pageable;
import org.springframework.data.domain.Sort;
import org.springframework.data.web.PageableDefault;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestHeader;
import org.springframework.web.bind.annotation.RestController;

import com.learning.auction.bid.BidService.PlacedBid;
import com.learning.auction.common.web.PageResponse;
import com.learning.auction.user.CurrentUser;

import jakarta.validation.Valid;
import jakarta.validation.constraints.DecimalMin;
import jakarta.validation.constraints.Digits;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;
import lombok.RequiredArgsConstructor;

@RestController
@RequiredArgsConstructor
class BidController {

    private final BidService bidService;
    private final CurrentUser currentUser;

    /**
     * Send a unique {@code Idempotency-Key} (e.g. a UUID generated by the client) per bid attempt.
     * If the network drops and the client retries with the same key, the original bid is returned
     * (200) instead of a second bid being placed (201).
     */
    @PostMapping("/api/auctions/{auctionId}/bids")
    ResponseEntity<PlaceBidResponse> placeBid(
            @PathVariable UUID auctionId,
            @RequestHeader(name = "Idempotency-Key", required = false) @Size(max = 100) String idempotencyKey,
            @Valid @RequestBody PlaceBidRequest request) {
        PlacedBid placed = bidService.placeBid(auctionId, currentUser.id(), request.amount(), idempotencyKey);
        return ResponseEntity
                .status(placed.replayed() ? HttpStatus.OK : HttpStatus.CREATED)
                .body(PlaceBidResponse.from(placed));
    }

    @GetMapping("/api/auctions/{auctionId}/bids")
    PageResponse<BidResponse> history(
            @PathVariable UUID auctionId,
            @PageableDefault(size = 50, sort = "amount", direction = Sort.Direction.DESC) Pageable pageable) {
        return PageResponse.of(bidService.history(auctionId, pageable), BidResponse::from);
    }

    @GetMapping("/api/users/me/bids")
    PageResponse<BidResponse> mine(
            @PageableDefault(size = 50, sort = "placedAt", direction = Sort.Direction.DESC) Pageable pageable) {
        return PageResponse.of(bidService.byBidder(currentUser.id(), pageable), BidResponse::from);
    }

    record PlaceBidRequest(@NotNull @DecimalMin("0.01") @Digits(integer = 17, fraction = 2) BigDecimal amount) {
    }

    record BidResponse(UUID id, UUID auctionId, UUID bidderId, BigDecimal amount, Instant placedAt) {

        static BidResponse from(Bid b) {
            return new BidResponse(b.getId(), b.getAuctionId(), b.getBidderId(), b.getAmount(), b.getPlacedAt());
        }
    }

    /** Includes the auction's new state so the client can update its UI without a second request. */
    record PlaceBidResponse(BidResponse bid, BigDecimal currentPrice, BigDecimal minimumNextBid,
                            int bidCount, Instant endTime, boolean endTimeExtended, boolean replayed) {

        static PlaceBidResponse from(PlacedBid p) {
            return new PlaceBidResponse(BidResponse.from(p.bid()), p.auction().getCurrentPrice(),
                    p.auction().minimumNextBid(), p.auction().getBidCount(), p.auction().getEndTime(),
                    p.endTimeExtended(), p.replayed());
        }
    }
}
